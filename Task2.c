/**
 * @brief Public function to print the tree in a vertical, human-readable format.
 * @param root The root of the tree to print.
 */
void printTreeVertical(TreeNode *root) {
    if (root == NULL) {
        printf("Tree is empty.\n");
        return;
    }
    printf("\nParse Tree Structure:\n");
    printf("%s\n", root->data); // Print the root node
    
    // Call the recursive helper to print children
    if (isUnary(root->data)) {
        // Unary node: only print the right child
        printTreeRecursiveHelper(root->right, "", true); 
    } else {
        // Binary or atom node
        printTreeRecursiveHelper(root->left, "", false); // Left child
        printTreeRecursiveHelper(root->right, "", true);  // Right child
    }
}

/**
 * @brief Recursively frees all nodes in the tree.
 * @param root The root of the tree/subtree to free.
 */
void freeTree(TreeNode *root) {
    if (root == NULL) {
        return; // Base case: empty subtree
    }
    // Recurse on children first (post-order traversal)
    freeTree(root->left);
    freeTree(root->right);
    
    // Free the string data (which was copied with strdup)
    free(root->data); 
    // Free the node structure itself
    free(root);       
}

// --- Private Helper Implementations ---

/**
 * @brief Allocates and initializes a new TreeNode.
 * @param value The string value for the node (will be copied).
 * @return A pointer to the new TreeNode.
 */
static TreeNode* makeNode(const char *value) {
    // Allocate memory for the node structure
    TreeNode* node = (TreeNode*)malloc(sizeof(TreeNode));
    if (!node) {
        fprintf(stderr, "Memory allocation failed for TreeNode.\n");
        exit(EXIT_FAILURE); // Critical failure
    }
    
    // Allocate memory and *copy* the string value
    node->data = strdup(value); 
    if (!node->data) {
        fprintf(stderr, "Memory allocation failed for TreeNode data.\n");
        free(node);
        exit(EXIT_FAILURE); // Critical failure
    }

    // Initialize children to NULL
    node->left = NULL;
    node->right = NULL;
    return node;
}

/**
 * @brief Checks if a token is a binary operator.
 * @param token The string token to check.
 * @return true if it's a binary operator, false otherwise.
 */
static bool isBinary(const char *token) {
    if (!token || strlen(token) != 1) return false; // Must be a single char
    char c = token[0];
    return (c == '+' || c == '*' || c == '>');
}

/**
 * @brief Checks if a token is a unary operator.
 * @param token The string token to check.
 * @return true if it's a unary operator, false otherwise.
 */
static bool isUnary(const char *token) {
    if (!token || strlen(token) != 1) return false; // Must be a single char
    char c = token[0];
    return (c == '~');
}

/**
 * @brief Recursive helper function for printing the tree vertically.
 * This function creates the "ASCII art" connectors.
 * @param root The current node to print.
 * @param prefix The line prefix (indentation and connectors like "    " or "|   ").
 * @param isLastChild true if this node is the last child of its parent
 * (determines if we use '`--' or '|--').
 */
static void printTreeRecursiveHelper(TreeNode *root, const char *prefix, bool isLastChild) {
    if (root == NULL)
        return; // Base case: empty child

    // Determine the connector string
    const char *connector = isLastChild ? "`-- " : "|-- ";
    // Print the current node
    printf("%s%s%s\n", prefix, connector, root->data);

    // Prepare the prefix for the *next* level of recursion
    char newPrefix[512]; // Buffer for the new prefix
    
    // Append to the prefix: "    " if last child, "|   " otherwise
    snprintf(newPrefix, sizeof(newPrefix)-1, "%s%s", prefix, (isLastChild ? "    " : "|   ")); 
    newPrefix[sizeof(newPrefix)-1] = '\0'; // Guarantee null termination

    // Recursively print children
    if (isUnary(root->data)) {
        // Unary node only has a right child
        // We treat it as the "last" child for connector purposes
        printTreeRecursiveHelper(root->right, newPrefix, true); 
    } else {
        // Binary node or Atom (Atom's children will be NULL, recursion will stop)
        printTreeRecursiveHelper(root->left, newPrefix, false); // Left child is not the last
        printTreeRecursiveHelper(root->right, newPrefix, true); // Right child is the last
    }
}