// === Stack for TreeNodes (used by iterative builder) ===

/**
 * @brief A simple stack structure for holding TreeNode pointers.
 * @note This is a separate stack implementation from the one in Task1.
 * It's used by the iterative prefixToTree algorithm to keep
 * track of parent nodes that are waiting for children.
 */
typedef struct {
    TreeNode** data; // Array of TreeNode pointers
    int top;         // Index of the top element
    int capacity;    // Max size of the stack
} NodeStack;

/**
 * @brief Creates a new stack for TreeNode pointers.
 * @param capacity The maximum number of nodes the stack can hold.
 * @return A pointer to the new NodeStack. Exits on allocation failure.
 */
static NodeStack* createNodeStack(int capacity) {
    NodeStack* ns = (NodeStack*)malloc(sizeof(NodeStack));
    if (!ns) { fprintf(stderr, "Failed to allocate NodeStack\n"); exit(1); }
    ns->data = (TreeNode**)malloc(sizeof(TreeNode*) * capacity);
    if (!ns->data) { fprintf(stderr, "Failed to allocate NodeStack data\n"); free(ns); exit(1); }
    ns->capacity = capacity;
    ns->top = -1; // Stack is initially empty
    return ns;
}

/**
 * @brief Checks if the NodeStack is empty.
 * @param ns The NodeStack.
 * @return 1 (true) if empty, 0 (false) otherwise.
 */
static int isNodeStackEmpty(NodeStack* ns) { return ns->top == -1; }

/**
 * @brief Peeks at the top TreeNode* of the stack without removing it.
 * @param ns The NodeStack.
 * @return The top TreeNode*, or NULL if the stack is empty.
 */
static TreeNode* node_peek(NodeStack* ns) { return (ns->top >= 0) ? ns->data[ns->top] : NULL; } 

/**
 * @brief Pushes a TreeNode* onto the stack.
 * @note Does not check for overflow (assumes capacity is sufficient).
 * @param ns The NodeStack.
 * @param node The TreeNode pointer to push.
 */
static void node_push(NodeStack* ns, TreeNode* node) { ns->data[++ns->top] = node; }

/**
 * @brief Pops a TreeNode* from the stack.
 * @param ns The NodeStack.
 * @return The popped TreeNode*, or NULL if the stack is empty.
 */
static TreeNode* node_pop(NodeStack* ns) { return (ns->top >= 0) ? ns->data[ns->top--] : NULL; }

/**
 * @brief Frees the memory used by the NodeStack (but not the TreeNodes it points to).
 * @param ns The NodeStack to free.
 */
static void freeNodeStack(NodeStack* ns) { free(ns->data); free(ns); }
// === END: NodeStack ===


// --- Public Function Definitions ---

/**
 * @brief Helper to check if a token is an atom (operand).
 * An atom is any token that is not a known operator.
 * @param token The string token to check.
 * @return true if the token is an atom, false otherwise.
 */
bool isAtom(const char *token) {
    if (!token || token[0] == '\0') return false;
    // It's an atom if it's NOT a known operator
    return !(isBinary(token) || isUnary(token));
}

/**
 * @brief Iteratively builds a parse tree from a prefix expression stack.
 *
 * This algorithm works by processing tokens one by one from the prefix stack
 * (which was generated by `task1_infixToPrefix`). It uses a *second* stack
 * (`NodeStack`) to keep track of parent nodes (operators) that are
 * waiting to be assigned children.
 *
 * @param prefix_stack The stack of prefix tokens (from Task1).
 * @return A pointer to the root TreeNode of the constructed parse tree.
 */
TreeNode* prefixToTree(Stack *prefix_stack) {
    if (prefix_stack == NULL || isEmpty(prefix_stack)) {
        return NULL; // Nothing to build
    }

    // 1. Get the first token: this must be the root of the tree.
    char* token = pop(prefix_stack);
    if (!token) return NULL;
    TreeNode* root = makeNode(token);
    free(token); // makeNode creates a copy

    // Node stack stores parent nodes waiting for children
    NodeStack* node_stack = createNodeStack(prefix_stack->capacity);

    // 2. If the root is an operator, it needs children.
    // Push it onto the node_stack to wait for them.
    if (!isAtom(root->data)) {
        node_push(node_stack, root);
    }

    // 3. Process remaining tokens from the prefix (string) stack
    while (!isEmpty(prefix_stack)) {
        // Get the parent node that's waiting for its *next* child.
        // We *peek* because it might need another child after this one.
        TreeNode* current_parent = node_peek(node_stack);
        
        // Error check: If no parent is waiting, but we have tokens,
        // the expression is malformed (too many operands).
        if (current_parent == NULL) {
             fprintf(stderr, "Error: Node stack empty but prefix stack has tokens (Malformed expression? Too many operands?).\n");
             while ((token = pop(prefix_stack)) != NULL) free(token); // Cleanup remaining tokens
             break; // Exit loop
        }

        // Get the next token from the input (this will be a child)
        token = pop(prefix_stack);
        if (!token) break; // Should not happen if loop condition is correct
        TreeNode* new_node = makeNode(token);
        free(token); // makeNode copies it

        // 4. Attach new_node to parent based on parent type
        bool attached = false;
        if (isUnary(current_parent->data)) {
            // Unary operator ('~') only gets a right child
            if (current_parent->right == NULL) {
                current_parent->right = new_node;
                // A unary parent is now "full" after one child.
                node_pop(node_stack); // Pop it from the waiting stack.
                attached = true;
            } else {
                 // This case should logically not be reachable
                 fprintf(stderr, "Error logic: Unary node '%s' trying to attach second child '%s'?\n", current_parent->data, new_node->data);
                 freeTree(new_node); break; // Error state
            }
        } else if (isBinary(current_parent->data)) {
            // Binary operator ('*', '+', '>') gets left child, then right child.
            if (current_parent->left == NULL) {
                // This is the first child; attach it to the left.
                current_parent->left = new_node;
                attached = true;
                // *Don't* pop parent yet, it still needs a right child.
            } else if (current_parent->right == NULL) {
                // This is the second child; attach it to the right.
                current_parent->right = new_node;
                // A binary parent is now "full" after two children.
                node_pop(node_stack); // Pop it from the waiting stack.
                attached = true;
            } else {
                 // This case should logically not be reachable
                 fprintf(stderr, "Error logic: Binary node '%s' trying to attach third child '%s'?\n", current_parent->data, new_node->data);
                 freeTree(new_node); break; // Error state
            }
        } else {
             // This should not happen, as only operators are pushed to node_stack
             fprintf(stderr, "Error logic: Atom node '%s' on node_stack?\n", current_parent->data);
             freeTree(new_node); break; // Error state
        }

        // 5. If the new node we just attached is *also* an operator,
        // push it onto the node_stack. It will now be the next node
        // waiting for *its* children.
        if (attached && !isAtom(new_node->data)) {
            node_push(node_stack, new_node);
        } else if (!attached) {
            // If we somehow didn't attach (error case), free the new node
            freeTree(new_node);
        }
    } // --- End of while loop ---

    // 6. Final Checks and Cleanup
    
    // If the node_stack is not empty, the expression was malformed
    // (e.g., " + a " -> missing an operand).
    if (!isNodeStackEmpty(node_stack)) {
         fprintf(stderr, "Warning: Node stack not empty after processing all tokens (Malformed expression? Operators missing operands?).\n");
         // Tree might be incomplete.
    }
    // This check is technically redundant with the one inside the loop,
    // but serves as a final safeguard.
     if (!isEmpty(prefix_stack)) {
         fprintf(stderr, "Warning: Prefix stack not empty after processing (Malformed expression? Too many operands?).\n");
         while ((token = pop(prefix_stack)) != NULL) free(token); // Cleanup
     }

    freeNodeStack(node_stack); // Free the helper stack
    return root; // Return the completed tree
}


